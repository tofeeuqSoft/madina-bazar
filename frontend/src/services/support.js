import api from './api';

export const supportApi = {
  dashboard: () => api.get('/support/dashboard').then((r) => r.data.data),
  reports: () => api.get('/support/reports').then((r) => r.data.data),
  tickets: (params) => api.get('/support/tickets', { params }).then((r) => r.data),
  ticket: (id) => api.get(`/support/tickets/${id}`).then((r) => r.data.data),
  createTicket: (body) => api.post('/support/tickets', body).then((r) => r.data.data),
  setStatus: (id, status) => api.patch(`/support/tickets/${id}/status`, { status }).then((r) => r.data.data),
  assign: (id, body) => api.patch(`/support/tickets/${id}/assign`, body).then((r) => r.data.data),
  autoAssign: (id) => api.post(`/support/tickets/${id}/auto-assign`).then((r) => r.data.data),
  ticketMessages: (id, params) => api.get(`/support/tickets/${id}/messages`, { params }).then((r) => r.data),
  replyTicket: (id, body) => api.post(`/support/tickets/${id}/messages`, body).then((r) => r.data.data),
  conversations: (params) => api.get('/support/conversations', { params }).then((r) => r.data),
  createConversation: (body) => api.post('/support/conversations', body || {}).then((r) => r.data.data),
  conversation: (id) => api.get(`/support/conversations/${id}`).then((r) => r.data.data),
  chatMessages: (id, params) => api.get(`/support/conversations/${id}/messages`, { params }).then((r) => r.data),
  replyChat: (id, body) => api.post(`/support/conversations/${id}/messages`, body).then((r) => r.data.data),
  patchConversation: (id, body) => api.patch(`/support/conversations/${id}`, body).then((r) => r.data.data),
  customer360: (id) => api.get(`/support/customers/${id}`).then((r) => r.data.data),
  search: (q) => api.get('/support/search', { params: { q } }).then((r) => r.data.data),
  notes: (params) => api.get('/support/notes', { params }).then((r) => r.data.data),
  addNote: (body) => api.post('/support/notes', body).then((r) => r.data.data),
  categories: () => api.get('/support/categories').then((r) => r.data.data),
  createCategory: (body) => api.post('/support/categories', body).then((r) => r.data.data),
  teams: () => api.get('/support/teams').then((r) => r.data.data),
  agents: () => api.get('/support/agents').then((r) => r.data.data),
  faq: (params) => api.get('/support/faq', { params }).then((r) => r.data.data),
  createFaq: (body) => api.post('/support/faq', body).then((r) => r.data.data),
  updateFaq: (id, body) => api.patch(`/support/faq/${id}`, body).then((r) => r.data.data),
  canned: () => api.get('/support/canned-responses').then((r) => r.data.data),
  createCanned: (body) => api.post('/support/canned-responses', body).then((r) => r.data.data),
  useCanned: (id, variables) => api.post(`/support/canned-responses/${id}/use`, { variables }).then((r) => r.data.data),
  feedback: () => api.get('/support/feedback').then((r) => r.data.data),
  notifications: () => api.get('/support/notifications').then((r) => r.data.data),
  audit: (params) => api.get('/support/audit-logs', { params }).then((r) => r.data.data),
  aiContext: (params) => api.get('/support/ai/context', { params }).then((r) => r.data.data),
  aiHandoff: (body) => api.post('/support/ai/handoff', body).then((r) => r.data.data),
};

export default supportApi;
